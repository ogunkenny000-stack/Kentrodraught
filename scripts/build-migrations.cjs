/* Deterministic incremental SQL bundle. Fresh databases need schema.sql first. */
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const directory = path.join(root, 'supabase/migrations');
const files = fs.readdirSync(directory).filter(file => file.endsWith('.sql')).sort();
const header = `-- GENERATED by node scripts/build-migrations.cjs; do not edit this bundle.
-- Existing installations: back up, review all changes and rehearse in isolated
-- Supabase staging before applying this incremental bundle as database owner.
-- Fresh installations: apply supabase/schema.sql ONCE, then this bundle.
-- Keep filename order. This file contains explicit transaction boundaries;
-- an error in a later migration does not undo earlier committed migrations.
-- The local regression harness checks reruns, authorization and rollback.
-- Hosted Auth, Realtime, extensions and deployment still need staging checks.
-- No reset script is included. Application rollback does not roll back SQL.
\n`;
const content = header + files.map(file => `-- BEGIN MIGRATION ${file}\n${fs.readFileSync(path.join(directory, file), 'utf8').trimEnd()}\n-- END MIGRATION ${file}\n`).join('\n');
const output = path.join(root, 'supabase/all_migrations_combined.sql');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(output, 'utf8') !== content) { console.error('Combined migrations are stale; run node scripts/build-migrations.cjs'); process.exitCode = 1; }
} else fs.writeFileSync(output, content);
